%% The parse transform that prepares an Erlang module for ExUnit.
%%
%% The header file ex_unit_erlang/include/ex_unit.hrl enables the parse
%% transform. A module does not enable the parse transform directly.
%%
%% The parse transform does the following for a module:
%%
%%   * Collects every `*_test/0' and `*_test/1' function as a test.
%%   * Removes the `-async', `-moduletag' and `-tag' attributes and records
%%     the values.
%%   * Encloses each test body in a try expression. The catch clause converts
%%     an error from an OTP assert macro to an ExUnit assertion error.
%%   * Generates and exports `__ex_unit__/0', `__ex_unit__/2' and
%%     `__ex_unit_erlang__/0'.
-module(ex_unit_erlang_transform).
-moduledoc false.

-export([parse_transform/2, format_error/1]).

-define(ADAPTER, 'Elixir.ExUnitErlang.Adapter').
-define(CALLBACKS, [setup, setup_all]).

-record(state, {
    module :: module() | undefined,
    async = false :: boolean(),
    moduletags = [] :: [term()],
    %% The tags that apply to the next test function. The newest tag is first.
    pending = [] :: [{erl_anno:anno(), term()}],
    %% {Name, Arity, Anno, Tags}. The newest test is first.
    tests = [] :: [{atom(), arity(), erl_anno:anno(), [term()]}],
    %% {Name, Arity, Anno}
    callbacks = [] :: [{atom(), arity(), erl_anno:anno()}],
    errors = [] :: [{erl_anno:anno(), term()}]
}).

-spec parse_transform([erl_parse:abstract_form()], [compile:option()]) ->
    [erl_parse:abstract_form()].
parse_transform(Forms0, _Options) ->
    {Forms1, State0} = lists:mapfoldl(fun form/2, #state{}, Forms0),
    State1 = check(State0),
    Forms2 = [F || F <- Forms1, F =/= drop],
    case State1#state.errors of
        [] ->
            inject(Forms2, State1);
        Errors ->
            %% The compiler prints an error form with the file and the line.
            [
                {error, {erl_anno:location(Anno), ?MODULE, Reason}}
             || {Anno, Reason} <- lists:reverse(Errors)
            ] ++ Forms2
    end.

-spec format_error(term()) -> iolist().
format_error({bad_async, Value}) ->
    io_lib:format("-async expects true or false, got: ~tp", [Value]);
format_error({bad_tag, Attr, Value}) ->
    io_lib:format(
        "-~ts expects an atom, a {Key, Value} tuple, a map, or a list of "
        "atoms and tuples, got: ~tp",
        [Attr, Value]
    );
format_error({reserved_tag, Attr, Key}) ->
    io_lib:format("-~ts cannot set '~ts': the tag is reserved by ExUnit", [Attr, Key]);
format_error({dangling_tag, Name, Arity}) ->
    io_lib:format(
        "-tag must be followed by a test function (*_test/0 or *_test/1), "
        "but it is followed by ~ts/~b",
        [Name, Arity]
    );
format_error(dangling_tag_eof) ->
    "-tag must be followed by a test function (*_test/0 or *_test/1)";
format_error({duplicate_test, Name}) ->
    io_lib:format(
        "test ~ts is defined with both arity 0 and arity 1; keep only one",
        [Name]
    );
format_error({duplicate_callback, Name}) ->
    io_lib:format(
        "callback ~ts is defined with both arity 0 and arity 1; keep only one",
        [Name]
    );
format_error({reserved_function, Name, Arity}) ->
    io_lib:format("~ts/~b is generated by ex_unit_erlang and cannot be defined", [Name, Arity]).

%%% ---------------------------------------------------------------------------
%%% Scanning
%%% ---------------------------------------------------------------------------

form({attribute, _, module, Module} = Form, State) ->
    {Form, State#state{module = Module}};
form({attribute, _, async, Value}, State) when is_boolean(Value) ->
    {drop, State#state{async = Value}};
form({attribute, Anno, async, Value}, State) ->
    {drop, add_error(Anno, {bad_async, Value}, State)};
form({attribute, Anno, moduletag, Value}, State) ->
    case check_tag(Value) of
        ok ->
            {drop, State#state{moduletags = State#state.moduletags ++ [Value]}};
        {error, Reason} ->
            {drop, add_error(Anno, tag_error(Reason, moduletag, Value), State)}
    end;
form({attribute, Anno, tag, Value}, State) ->
    case check_tag(Value) of
        ok ->
            {drop, State#state{pending = [{Anno, Value} | State#state.pending]}};
        {error, Reason} ->
            {drop, add_error(Anno, tag_error(Reason, tag, Value), State)}
    end;
form({function, Anno, Name, Arity, Clauses} = Form, State0) ->
    case classify(Name, Arity) of
        test ->
            Tags = lists:reverse([Tag || {_, Tag} <- State0#state.pending]),
            Test = {Name, Arity, Anno, Tags},
            State1 = State0#state{pending = [], tests = [Test | State0#state.tests]},
            Module = State1#state.module,
            {{function, Anno, Name, Arity, [wrap_clause(C, Module) || C <- Clauses]}, State1};
        callback ->
            State1 = dangling(State0, {dangling_tag, Name, Arity}),
            {Form, State1#state{callbacks = [{Name, Arity, Anno} | State1#state.callbacks]}};
        reserved ->
            {Form, add_error(Anno, {reserved_function, Name, Arity}, State0)};
        other ->
            {Form, dangling(State0, {dangling_tag, Name, Arity})}
    end;
form({eof, _} = Form, State) ->
    {Form, dangling(State, dangling_tag_eof)};
form(Form, State) ->
    {Form, State}.

classify('__ex_unit__', Arity) when Arity =:= 0; Arity =:= 2 -> reserved;
classify('__ex_unit_erlang__', 0) -> reserved;
classify(Name, Arity) when Arity =:= 0; Arity =:= 1 ->
    case lists:member(Name, ?CALLBACKS) of
        true ->
            callback;
        false ->
            case lists:suffix("_test", atom_to_list(Name)) of
                true -> test;
                false -> other
            end
    end;
classify(_Name, _Arity) ->
    other.

dangling(#state{pending = []} = State, _Reason) ->
    State;
dangling(#state{pending = Pending} = State, Reason) ->
    {Anno, _} = lists:last(Pending),
    add_error(Anno, Reason, State#state{pending = []}).

add_error(Anno, Reason, State) ->
    State#state{errors = [{Anno, Reason} | State#state.errors]}.

%% Checks that involve more than one form. A test name or a callback name
%% must not have both arity 0 and arity 1. ExUnit identifies a test by name
%% only.
check(State0) ->
    State1 = duplicates(State0#state.tests, duplicate_test, State0),
    duplicates(State1#state.callbacks, duplicate_callback, State1).

duplicates(Entries, Reason, State) ->
    %% Each name produces one error, at the definition with arity 1.
    lists:foldl(
        fun(Entry, Acc) ->
            Name = element(1, Entry),
            Anno = element(3, Entry),
            Others = [E || E <- Entries, element(1, E) =:= Name, element(2, E) =/= element(2, Entry)],
            case Others of
                [Other | _] when element(2, Other) < element(2, Entry) ->
                    add_error(Anno, {Reason, Name}, Acc);
                _ ->
                    Acc
            end
        end,
        State,
        Entries
    ).

%%% ---------------------------------------------------------------------------
%%% Tags
%%% ---------------------------------------------------------------------------

-define(RESERVED_TAGS, [module, file, line, test, async, registered, describe]).

check_tag(Tag) when is_atom(Tag) -> check_key(Tag);
check_tag({Key, _}) when is_atom(Key) -> check_key(Key);
check_tag(Map) when is_map(Map) -> check_tags(maps:to_list(Map));
check_tag([_ | _] = List) -> check_tags(List);
check_tag(_) -> {error, bad_tag}.

check_tags([]) ->
    ok;
check_tags([Tag | Rest]) when is_atom(Tag); is_tuple(Tag) ->
    case check_tag(Tag) of
        ok -> check_tags(Rest);
        Error -> Error
    end;
check_tags(_) ->
    {error, bad_tag}.

check_key(Key) ->
    case lists:member(Key, ?RESERVED_TAGS) of
        true -> {error, {reserved, Key}};
        false -> ok
    end.

tag_error(bad_tag, Attr, Value) -> {bad_tag, Attr, Value};
tag_error({reserved, Key}, Attr, _Value) -> {reserved_tag, Attr, Key}.

%%% ---------------------------------------------------------------------------
%%% Code generation
%%% ---------------------------------------------------------------------------

%% Encloses the body of a test clause in a try expression. Reasons:
%%
%%   * The catch clause converts an error from an OTP assert macro to an
%%     ExUnit assertion error.
%%   * A call inside a try expression is not a tail call. The test function
%%     therefore stays in the stacktrace. ExUnit uses the stacktrace entry of
%%     the test function to print the failing source line.
wrap_clause({clause, Anno, Patterns, Guards, Body}, Module) ->
    G = erl_anno:set_generated(true, Anno),
    Class = {var, G, '__ExUnitErlangClass'},
    Reason = {var, G, '__ExUnitErlangReason'},
    Stack = {var, G, '__ExUnitErlangStack'},
    Reraise =
        {call, G, {remote, G, {atom, G, ?ADAPTER}, {atom, G, reraise}}, [
            {atom, G, Module}, Class, Reason, Stack
        ]},
    Catch = {clause, G, [{tuple, G, [Class, Reason, Stack]}], [], [Reraise]},
    {clause, Anno, Patterns, Guards, [{'try', G, Body, [], [Catch], []}]}.

inject(Forms, State) ->
    {Head, Tail} = lists:splitwith(fun(F) -> not is_function_or_eof(F) end, Forms),
    {Body, Eof} = lists:splitwith(fun(F) -> element(1, F) =/= eof end, Tail),
    Head ++ [exports(State)] ++ Body ++ generated(State) ++ Eof.

is_function_or_eof({function, _, _, _, _}) -> true;
is_function_or_eof({eof, _}) -> true;
is_function_or_eof(_) -> false.

exports(#state{tests = Tests, callbacks = Callbacks}) ->
    G = gen(1),
    TestExports = lists:usort(
        lists:append([[{Name, Arity}, {Name, 1}] || {Name, Arity, _, _} <- Tests])
    ),
    CallbackExports = [{Name, Arity} || {Name, Arity, _} <- Callbacks],
    {attribute, G, export,
        [{'__ex_unit__', 0}, {'__ex_unit__', 2}, {'__ex_unit_erlang__', 0}] ++
            TestExports ++ CallbackExports}.

generated(#state{module = Module, tests = Tests0, callbacks = Callbacks} = State) ->
    Tests = lists:reverse(Tests0),
    Spec = #{
        async => State#state.async,
        moduletags => State#state.moduletags,
        setup_all => lists:keymember(setup_all, 1, Callbacks),
        tests => [{Name, line(Anno), Tags} || {Name, _Arity, Anno, Tags} <- Tests]
    },
    G = gen(1),
    Ctx = {var, G, 'Context'},
    [
        %% __ex_unit_erlang__() -> Spec.
        function(G, '__ex_unit_erlang__', [], [erl_parse:abstract(Spec, 1)]),
        %% __ex_unit__() -> Adapter:test_module(Module).
        function(G, '__ex_unit__', [], [remote(G, test_module, [{atom, G, Module}])]),
        %% __ex_unit__(setup_all | setup, Context) -> Context.
        {function, G, '__ex_unit__', 2, [
            callback_clause(G, Module, Kind, Callbacks, Ctx)
         || Kind <- [setup_all, setup]
        ]}
    ] ++
        %% For each test with arity 0: name_test(_Context) -> name_test().
        [
            function(gen(line(Anno)), Name, [{var, gen(line(Anno)), '_'}], [
                {call, gen(line(Anno)), {atom, gen(line(Anno)), Name}, []}
            ])
         || {Name, 0, Anno, _} <- Tests
        ].

callback_clause(G, Module, Kind, Callbacks, Ctx) ->
    Body =
        case lists:keyfind(Kind, 1, Callbacks) of
            {Kind, Arity, _} ->
                Fun = {'fun', G, {function, Kind, Arity}},
                remote(G, callback, [{atom, G, Module}, {atom, G, Kind}, Fun, Ctx]);
            false ->
                Ctx
        end,
    {clause, G, [{atom, G, Kind}, Ctx], [], [Body]}.

function(G, Name, Args, Body) ->
    {function, G, Name, length(Args), [{clause, G, Args, [], Body}]}.

remote(G, Function, Args) ->
    {call, G, {remote, G, {atom, G, ?ADAPTER}, {atom, G, Function}}, Args}.

gen(Line) ->
    erl_anno:set_generated(true, erl_anno:new(Line)).

line(Anno) ->
    erl_anno:line(Anno).
